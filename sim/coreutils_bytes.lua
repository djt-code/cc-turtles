-- sim/coreutils_bytes.lua
--
-- The byte-level utilities in a shellworld: tee, od, strings and printf,
-- with their options, files, "-", standard input from the keyboard and a
-- pipe, missing files, and the output formats.
local PROJ = ...
package.path = PROJ .. "/lib/?.lua;" .. PROJ .. "/sim/lib/?.lua;" .. package.path
local M = require("mock")
local SW = require("shellworld")
local check = M.check

local W = SW.new(PROJ)
local function show(s)
    return (tostring(s):gsub("[%c\128-\255]", function(c) return c == "\n" and "|" or "\\" .. c:byte() end))
end
local function is(name, r, out, status, err)
    local ok = r.ok and r.out == out and r.status == (status or 0)
        and (err == nil or r.err[1] == err)
    check(name, ok, show(r.out) .. " status " .. tostring(r.status) .. " " .. tostring(r.errText or r.error))
end

--------------------------------------------------------------------------
-- tee
--------------------------------------------------------------------------
local r = W:run("tee", "t1.txt", "-", { stdin = "a\nb\n", pipe = true })
is("tee: a pipe to stdout and two files", r, "a\nb\n")
check("tee: the files hold the copy, '-' is a file named -", W:read("t1.txt") == "a\nb\n" and W:read("-") == "a\nb\n")
r = W:run("tee", "-a", "t1.txt", { stdin = "c\n" })
is("tee -a from the keyboard appends", r, "c\n")
check("tee -a: file appended", W:read("t1.txt") == "a\nb\nc\n", show(W:read("t1.txt")))
r = W:run("tee", "t1.txt", { stdin = "new\n", pipe = true })
check("tee without -a replaces", W:read("t1.txt") == "new\n")
r = W:run("tee", "-i", "rom/x", "t2.txt", { stdin = "z", pipe = true })
is("tee: an unwritable file is reported, the copy goes on, status 1", r, "z", 1, "tee: rom/x: Permission denied")
check("tee: the other file still written", W:read("t2.txt") == "z")
local long = string.rep("line of text\r\n", 3000) .. "no newline"
r = W:run("tee", "t3.txt", { stdin = long, pipe = true })
check("tee: 3000 CRLF lines from a pipe, yielding, last line unterminated", r.ok and r.out == long, tostring(r.error))
check("tee: the file is byte for byte the same", W:read("t3.txt") == long)
W:dir("d")
r = W:run("tee", "d", { stdin = "x\n", pipe = true })
is("tee: a directory operand", r, "x\n", 1, "tee: d: Is a directory")
r = W:run("tee", "-q", { stdin = "", pipe = true })
check("tee: bad option is a usage error, status 2", r.status == 2 and r.err[1] == "tee: illegal option -- q")

--------------------------------------------------------------------------
-- od
--------------------------------------------------------------------------
W:file("abc.txt", "abc\n")
r = W:run("od", "abc.txt", { pipeOut = true })
is("od: default -t o2, octal offsets, final offset", r, "0000000 061141 005143\n0000004\n")
r = W:run("od", "-c", { stdin = "abc\n", pipe = true })
is("od -c from a pipe", r, "0000000   a   b   c  \\n\n0000004\n")
r = W:run("od", "-b", "-", { stdin = "abc\n", pipe = true })
is("od -b on '-'", r, "0000000 141 142 143 012\n0000004\n")
r = W:run("od", "-An", "-tx1", "abc.txt", { pipeOut = true })
is("od -An -tx1: no offsets", r, " 61 62 63 0a\n")
r = W:run("od", "-x", "abc.txt", { pipeOut = true })
is("od -x: little-endian words", r, "0000000 6261 0a63\n0000004\n")
W:file("odd.bin", "abc")
r = W:run("od", "-x", "odd.bin", { pipeOut = true })
is("od -x: a short last word is zero-filled", r, "0000000 6261 0063\n0000003\n")
W:file("ff.bin", "\255\255")
r = W:run("od", "-s", "ff.bin", { pipeOut = true })
is("od -s: signed words", r, "0000000     -1\n0000002\n")
r = W:run("od", "-d", "ff.bin", { pipeOut = true })
is("od -d: unsigned words", r, "0000000 65535\n0000002\n")
r = W:run("od", "-o", "ff.bin", { pipeOut = true })
is("od -o: octal words", r, "0000000 177777\n0000002\n")
r = W:run("od", "-t", "d1u1", "ff.bin", { pipeOut = true })
is("od -t d1u1: two types, two lines", r, "0000000   -1   -1\n         255  255\n0000002\n")
W:file("ff8.bin", string.rep("\255", 8))
r = W:run("od", "-An", "-tu8", "-td8", "-txL", "-to8", "ff8.bin", { pipeOut = true })
is("od: 8-byte values exact", r, "   18446744073709551615\n                     -1\n       ffffffffffffffff\n 1777777777777777777777\n")
W:file("one.bin", "\1\0\0\0")
r = W:run("od", "-An", "-t", "x", "-tdS", "one.bin", { pipeOut = true })
is("od: default size 4, S = 2", r, "      00000001\n      1      0\n")
W:file("named.bin", "\0\n\127 A\128")
r = W:run("od", "-An", "-ta", "named.bin", { pipeOut = true })
is("od -t a: named characters, high bit ignored", r, " nul  nl del  sp   A nul\n")
r = W:run("od", "-c", "named.bin", { pipeOut = true })
is("od -c: escapes and octal", r, "0000000  \\0  \\n 177       A 200\n0000006\n")
r = W:run("od", "-c", "-tx1", "-Ad", "abc.txt", { pipeOut = true })
is("od -c -t x1 -Ad: fields line up", r, "0000000   a   b   c  \\n\n         61  62  63  0a\n0000004\n")
W:file("dup.txt", string.rep("A", 48) .. "B")
r = W:run("od", "-Ax", "-tx1", "dup.txt", { pipeOut = true })
local row = string.rep(" 41", 16)
is("od: repeated lines become *", r, "000000" .. row .. "\n*\n000030 42\n000031\n")
r = W:run("od", "-v", "-An", "-tx1", "dup.txt", { pipeOut = true })
is("od -v: every line", r, row .. "\n" .. row .. "\n" .. row .. "\n 42\n")
W:file("six.txt", "abcdef")
r = W:run("od", "-j", "2", "-N2", "six.txt", { pipeOut = true })
is("od -j 2 -N2: offsets count the skip", r, "0000002 062143\n0000004\n")
r = W:run("od", "-j0x1", "-N", "010", "-c", "six.txt", { pipeOut = true })
is("od -j 0x1 -N 010 (hex, octal)", r, "0000001   b   c   d   e   f\n0000006\n")
W:file("big.bin", string.rep("x", 1030))
r = W:run("od", "-j1k", "-An", "-c", "big.bin", { pipeOut = true })
is("od -j 1k", r, "   x   x   x   x   x   x\n")
W:file("cd.txt", "cd")
r = W:run("od", "-tx1", "-Ao", "six.txt", "cd.txt", { pipeOut = true })
is("od: files are one stream", r, "0000000 61 62 63 64 65 66 63 64\n0000010\n")
r = W:run("od", "-j", "10", "six.txt", { pipeOut = true })
is("od: skip past the end, status 1", r, "", 1, "od: cannot skip past end of combined input")
r = W:run("od", "nope", "six.txt", { pipeOut = true })
is("od: a missing file reported, the rest dumped", r, "0000000 061141 062143 063145\n0000006\n", 1,
    "od: nope: No such file or directory")
r = W:run("od", "-t", "q", "six.txt", { pipeOut = true })
check("od -t q: usage error 2", r.status == 2 and r.out == "" and r.err[1] == "od: invalid type string: q")
r = W:run("od", "-A", "z", "six.txt", { pipeOut = true })
check("od -A z: usage error 2", r.status == 2)
r = W:run("od", "-j", "08", "six.txt", { pipeOut = true })
check("od -j 08: not octal, usage error 2", r.status == 2 and r.err[1] == "od: invalid skip: 08")
r = W:run("od", "-t", "", "six.txt", { pipeOut = true })
check("od -t '': usage error 2", r.status == 2 and r.err[1] == "od: empty type string")
W:file("big.dat", string.rep("0123456789abcdefXYZ", 2000))
r = W:run("od", "-tx1", "big.dat", { pipeOut = true })
check("od: a 38000-byte file, yielding as it goes", r.ok and r.status == 0
    and select(2, r.out:gsub("\n", "")) == 2376 and r.out:sub(-8) == "0112160\n", show(r.out:sub(-40)))
r = W:run("od", { stdin = "hi\n" })
is("od from the keyboard (Ctrl+T ends it)", r, "0000000 064550 000012\n0000003\n")
r = W:run("od", "-c", { stdin = "", pipe = true })
is("od: empty input", r, "0000000\n")

