-- strings
--------------------------------------------------------------------------
W:file("bin.dat", "ab\0hello\1world!!\nxyz\0longer string")
r = W:run("strings", "bin.dat", { pipeOut = true })
is("strings: runs of 4 or more", r, "hello\nworld!!\nlonger string\n")
r = W:run("strings", "-a", "-n", "3", "bin.dat", { pipeOut = true })
is("strings -a -n 3", r, "hello\nworld!!\nxyz\nlonger string\n")
r = W:run("strings", "-td", "bin.dat", { pipeOut = true })
is("strings -t d", r, "3 hello\n9 world!!\n21 longer string\n")
r = W:run("strings", "-t", "o", "-n3", "bin.dat", { pipeOut = true })
is("strings -t o", r, "3 hello\n11 world!!\n21 xyz\n25 longer string\n")
r = W:run("strings", "-tx", "bin.dat", "bin.dat", { pipeOut = true })
is("strings -t x, offsets per file", r, "3 hello\n9 world!!\n15 longer string\n3 hello\n9 world!!\n15 longer string\n")
r = W:run("strings", { stdin = "\1\2abcdef\3", pipe = true })
is("strings from a pipe", r, "abcdef\n")
r = W:run("strings", "-", { stdin = "typed words\n" })
is("strings - from the keyboard", r, "typed words\n")
r = W:run("strings", "nope", { pipeOut = true })
is("strings: missing file", r, "", 1, "strings: nope: No such file or directory")
W:file("many.dat", string.rep("word\0", 5000))
r = W:run("strings", "many.dat", { pipeOut = true })
check("strings: 5000 runs, yielding as it goes", r.ok and r.out == string.rep("word\n", 5000))
r = W:run("strings", "-n", "0", "bin.dat", { pipeOut = true })
check("strings -n 0: usage error 2", r.status == 2)
r = W:run("strings", "-t", "q", "bin.dat", { pipeOut = true })
check("strings -t q: usage error 2", r.status == 2)

