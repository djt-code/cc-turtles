-- printf
--------------------------------------------------------------------------
local function pf(...)
    local a = { ... }
    a[#a + 1] = { pipeOut = true }
    return W:run("printf", table.unpack(a))
end
is("printf: the format reused across arguments", pf("%s-%d\\n", "a", "1", "b", "2"), "a-1\nb-2\n")
is("printf: width, left, precision on %s", pf("%5s|%-5s|%.2s\\n", "ab", "cd", "xyz"), "   ab|cd   |xy\n")
is("printf: %d %i %o %u %x %X", pf("%d %i %o %u %x %X\\n", "42", "-7", "8", "3", "255", "255"), "42 -7 10 3 ff FF\n")
is("printf: flags 0 - + space and precision", pf("%05d|%-4d|%+d|% d|%.3d|%6.3d\\n", "42", "7", "5", "5", "7", "-7"),
    "00042|7   |+5| 5|007|  -007\n")
is("printf: # flag", pf("%#o %#x %#X\\n", "8", "255", "255"), "010 0xff 0XFF\n")
is("printf: negative unsigned is two's complement", pf("%u %x\\n", "-1", "-1"), "18446744073709551615 ffffffffffffffff\n")
is("printf: %e %f %g %E %G", pf("%e %f %g %.2f %E %G\\n", "1234.5", "1.5", "0.0001", "3.14159", "1.5", "1e-10"),
    "1.234500e+03 1.500000 0.0001 3.14 1.500000E+00 1E-10\n")
is("printf: %8.3f and %-8.1e", pf("[%8.3f][%-9.1e]\\n", "2.5", "12345"), "[   2.500][1.2e+04  ]\n")
is("printf: %c takes the first character", pf("%c%c%3c\\n", "hello", "world", "x"), "hw  x\n")
is("printf: %b escapes", pf("%b|\\n", "a\\tb\\0101\\\\"), "a\tbA\\|\n")
is("printf: %b \\c stops all output", pf("%b|%s\\n", "x\\cy", "z"), "x")
is("printf: format escapes and \\ddd", pf("a\\tb\\101\\q\\n"), "a\tbA\\q\n")
is("printf: %%", pf("100%%\\n"), "100%\n")
is("printf: 'c gives a character code", pf("%d %d\\n", "'A", "\"a"), "65 97\n")
is("printf: 0x hex and 0 octal arguments", pf("%d %d %d\\n", "0x10", "010", "+3"), "16 8 3\n")
is("printf: missing arguments are empty or 0", pf("%s|%d|%f|\\n"), "|0|0.000000|\n")
is("printf: a partial last round", pf("%s %s\\n", "a", "b", "c"), "a b\nc \n")
is("printf: no conversions, written once", pf("hi\\n", "a", "b"), "hi\n")
is("printf: a bad number is 0, status 1", pf("%d\\n", "abc"), "0\n", 1, "printf: abc: expected numeric value")
is("printf: a partly numeric argument", pf("%d|%.1f\\n", "12abc", "1.5x"), "12|1.5\n", 1, "printf: 12abc: not completely converted")
is("printf: 09 is not octal", pf("%d\\n", "09"), "0\n", 1, "printf: 09: not completely converted")
is("printf: %.d and %.0x of 0 print no digits", pf("[%.d][%.0x][%#.0o]\\n", "0", "0", "0"), "[][][0]\n")
r = pf("a%1000f", "1")
check("printf: a float spec Lua refuses does not crash", r.ok and r.out:sub(1, 1) == "a"
    and (r.status == 0 or r.err[1] == "printf: %1000f: invalid conversion"), tostring(r.error))
is("printf: -- before the format", pf("--", "%s\\n", "x"), "x\n")
is("printf: format starting with -", pf("-%s-\\n", "x"), "-x-\n")
is("printf: invalid conversion, status 1", pf("a%zb", "1"), "a", 1, "printf: %z: invalid conversion")
r = W:run("printf", { pipeOut = true })
check("printf with no format: usage, status 2", r.status == 2 and r.err[1] == "usage: printf format [argument...]")
r = W:run("printf", "%s\\n", "screen")
is("printf to the screen", r, "screen\n")
r = W:sh('printf "%s = %d\\n" "a b" 7')
is("printf through the shell", r, "a b = 7\n")
